create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins
    where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- 2. Jadual listing
create table if not exists public.listings (
  id                      bigint generated by default as identity primary key,
  slug                    text unique,
  status                  text not null default 'draf'
                          check (status in ('draf', 'dijual', 'terjual')),
  jenis                   text not null default 'Teres 2 Tingkat',
  taman                   text not null default '',
  kawasan                 text not null default '',
  negeri                  text not null default 'Selangor',
  harga                   numeric(12, 0),
  bilik                   smallint,
  bilik_air               smallint,
  keluasan_kps            integer,
  pegangan                text not null default 'Pegangan bebas',
  penerangan              text not null default '',
  gambar                  jsonb not null default '[]'::jsonb,  -- [{ "path": "...", "url": "..." }], pertama = utama
  urutan                  integer not null default 0,           -- susunan drag & drop
  hantar_telegram         boolean not null default true,
  telegram_dihantar_pada  timestamptz,
  kongsi_crm              boolean not null default true,
  tarikh_terjual          date,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now()
);

create index if not exists listings_status_urutan_idx on public.listings (status, urutan);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists listings_updated_at on public.listings;
create trigger listings_updated_at
  before update on public.listings
  for each row execute function public.set_updated_at();

-- 3. Keselamatan (Row Level Security)
alter table public.listings enable row level security;

drop policy if exists "Awam baca listing aktif" on public.listings;
create policy "Awam baca listing aktif"
  on public.listings for select
  to anon, authenticated
  using (status in ('dijual', 'terjual') or public.is_admin());

drop policy if exists "Admin tambah listing" on public.listings;
create policy "Admin tambah listing"
  on public.listings for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "Admin ubah listing" on public.listings;
create policy "Admin ubah listing"
  on public.listings for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admin padam listing" on public.listings;
create policy "Admin padam listing"
  on public.listings for delete
  to authenticated
  using (public.is_admin());

grant usage on schema public to anon, authenticated;
grant select on public.listings to anon, authenticated;
grant insert, update, delete on public.listings to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.is_admin() to anon, authenticated;

